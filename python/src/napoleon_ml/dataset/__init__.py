def __getattr__(name: str) -> object:
    if name in _PYTORCH_EXPORTS:
        module = import_module("napoleon_ml.dataset.pytorch")
        return getattr(module, name)

    raise AttributeError(f"module {__name__!r} has no attribute {name!r}")
